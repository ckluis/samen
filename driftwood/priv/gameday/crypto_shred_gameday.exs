section.("7. Red paths — the oracle FAILS a decryptable copy in each tier")

alias Samen.NoPlaintextPii
alias Samen.NoPlaintextPii.Context
alias Samen.NoPlaintextPii.Tiers.PostShred

# A post-shred context over the LIVE repo, replica declared absent.
post_ctx = fn subject, overrides ->
  Context.build(Keyword.merge([repo: Repo, subject_id: subject, resources: [], replica: :none], overrides))
end

find_v = fn findings, subj ->
  Enum.find(findings, &(&1.subject == subj and &1.severity == :violation))
end

# RP-live: a driver seeded but NOT shredded → live tier still decrypts → violation.
rp = GD.seed_driver_across_tiers(repo: Repo)
live_findings = PostShred.DbContent.check(post_ctx.(rp.driver_id, []))
check.("RED (live tier): an un-shredded driver's vault STILL DECRYPTS → oracle violation",
  find_v.(live_findings, "live") != nil)
# clean it up so it does not pollute later runs
{:ok, _} = Samen.Erasure.shred(rp.driver_id, repo: Repo)

# RP-registered_non_pii: shred, then put plaintext BACK into the non_pii! column.
rp2 = GD.seed_driver_across_tiers(repo: Repo)
{:ok, _} = Samen.Erasure.shred(rp2.driver_id, repo: Repo)
Repo.query!("UPDATE drv_driver SET drv_cdl_state = 'TX' WHERE drv_id = $1", [Ecto.UUID.dump!(rp2.driver_id)])
npi_findings = PostShred.DbContent.check(post_ctx.(rp2.driver_id, []))
check.("RED (registered_non_pii): an un-redacted non_pii! residue → oracle violation",
  find_v.(npi_findings, "registered_non_pii") != nil)
# re-redact for hygiene
Repo.query!("UPDATE drv_driver SET drv_cdl_state = '[REDACTED_NON_PII]' WHERE drv_id = $1", [Ecto.UUID.dump!(rp2.driver_id)])

# RP-kms-absent: a never-keyed subject → attest :absent → violation (positive
# tombstone required, not mere absence).
never_keyed = Ecto.UUID.generate()
kms_findings = PostShred.KmsAttestation.check(post_ctx.(never_keyed, []))
check.("RED (kms): a never-keyed subject attests :absent → oracle violation (positive tombstone required)",
  Enum.any?(kms_findings, &(&1.severity == :violation)))

# RP-rollup-resurrect: the pre-shred rollup counted the driver. If the erasure DID
# NOT govern the rollup, the driver survives in the derived aggregate. Sabotage the
# persisted report's rollup arm to prove the oracle catches an un-governed rollup.
rp3 = GD.seed_driver_across_tiers(repo: Repo)
{:ok, %{report: rep3}} = Samen.Erasure.shred(rp3.driver_id, repo: Repo)
# Drop the rollup arm from the persisted report (Ecto handles the jsonb encoding).
import Ecto.Query, only: [from: 2]
Repo.update_all(
  from(r in Samen.Erasure.Report, where: r.id == ^rep3.id),
  set: [tiers: Map.put(rep3.tiers, "rollups", [])]
)
rollup_findings = PostShred.DbContent.check(post_ctx.(rp3.driver_id, []))
check.("RED (rollup): a registered rollup ABSENT from the erasure report → oracle violation (no resurrection allowed)",
  find_v.(rollup_findings, "rollup") != nil)

# CDL-specific unrecoverability across ALL tiers (the task's named red path).
cdl_wrong_key = case Samen.Vault.scan_no_wrong_key(d, Repo) do
  {:ok, :no_cross_decrypt} -> true
  {:error, :unsupported} -> true  # documented seam on the production adapter
  _ -> false
end
check.("RED (CDL cross-tier): the CDL number is unrecoverable across all tiers post-shred (no wrong-key decrypt)", cdl_wrong_key)

# ===========================================================================
# 8. ANTI-TAUTOLOGY — sabotage one tier's shred, watch the oracle catch it
# ===========================================================================
section.("8. Anti-tautology probe — sabotage one tier's shred, the oracle catches it, then revert")

# Seed + shred a fresh driver (green). Then SABOTAGE the shred by REVERSING the
# key-destruction at the KMS store's file layer (a project-local scratch keystore we
# fully control) — delete the tombstone, regenerate the subject DEK, and re-store the
# CDL under it. This is a literal "the shred did not take" (a half-shred / a botched
# KMS destruction): a decryptable copy of the CDL is back on the LIVE tier. The oracle
# MUST catch it. Then revert (re-shred) and confirm the oracle goes GREEN — proving
# the flip is real, not a tautology.
probe = GD.seed_driver_across_tiers(repo: Repo)
pd = probe.driver_id

# GREEN baseline: shred, oracle live tier clean.
{:ok, _} = Samen.Erasure.shred(pd, repo: Repo)
green = PostShred.DbContent.check(post_ctx.(pd, []))
check.("ANTI-TAUT baseline: after a real shred the live tier is CLEAN (a :pass, not a :violation)",
  NoPlaintextPii.violations(green) == [] and Enum.any?(green, &(&1.subject == "live" and &1.severity == :pass)))

# SABOTAGE (scratch keystore file layer): reverse the key destruction, re-key, and
# re-store the CDL so a decryptable copy is back on the live tier.
subjects_dir = Path.join([kms_dir, "subjects"])
tomb = Path.join(subjects_dir, "#{pd}.tombstone")
_ = File.rm(tomb)
{:ok, _} = Samen.Kms.adapter().generate_subject_key(pd)
# Re-store the CDL under the resurrected key (a fresh active vault row that decrypts).
{:ok, _} = Samen.Vault.store_field(pd, :pii_cdl, :cdl_number, probe.cdl_plaintext, Repo)

sabotaged = PostShred.DbContent.check(post_ctx.(pd, []))
caught = find_v.(sabotaged, "live") != nil
check.("ANTI-TAUT sabotage: reversing the shred (resurrected key + re-stored CDL) → oracle FLIPS to a live-tier violation", caught)

# REVERT: re-shred to restore the sealed state (key destroyed, rows sealed).
{:ok, _} = Samen.Erasure.shred(pd, repo: Repo)
reverted = PostShred.DbContent.check(post_ctx.(pd, []))
check.("ANTI-TAUT revert: re-shred re-seals the tier → oracle GREEN again (the flip was real, not a tautology)",
  NoPlaintextPii.violations(reverted) == [])

